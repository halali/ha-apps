#!/usr/bin/env bash
# shellcheck shell=bash
# AppFlowy all-in-one add-on entrypoint.
#
# Responsibilities (run once, before the process manager takes over):
#   1. Load / generate persistent secrets (JWT, DB, S3) in /config
#   2. Resolve user options (HA injects them as env; fall back to options.json)
#   3. Compute the derived service environment and write it to a single file
#      that every service wrapper sources
#   4. Initialise the PostgreSQL data directory (extensions + auth schema)
#   5. Render the nginx gateway + ingress landing page
#   6. Hand off to supervisord, which runs all long-lived services
set -euo pipefail

CONFIG_DIR="/config"
SECRETS_FILE="${CONFIG_DIR}/secrets.env"
ENV_FILE="/etc/appflowy/appflowy.env"
OPTIONS_JSON="/data/options.json"

log() { echo "[appflowy] $*"; }

mkdir -p /etc/appflowy /run/appflowy "${CONFIG_DIR}" \
         "${CONFIG_DIR}/minio-data" "${CONFIG_DIR}/redis"

# ── 1. Persistent secrets ────────────────────────────────────────────────────
if [[ ! -f "${SECRETS_FILE}" ]]; then
    log "Generating persistent secrets (first run)…"
    (
        umask 077
        {
            echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
            echo "GOTRUE_JWT_SECRET=$(openssl rand -hex 32)"
            echo "APPFLOWY_S3_ACCESS_KEY=af$(openssl rand -hex 8)"
            echo "APPFLOWY_S3_SECRET_KEY=$(openssl rand -hex 24)"
        } > "${SECRETS_FILE}"
    )
    chmod 600 "${SECRETS_FILE}"
fi
# shellcheck disable=SC1090
source "${SECRETS_FILE}"

# ── 2. User options ──────────────────────────────────────────────────────────
# HA Supervisor exposes each add-on option as an environment variable, but we
# also fall back to /data/options.json so the add-on works either way.
opt() {
    local key="$1" def="${2:-}" val="${!1:-}"
    if [[ -z "${val}" && -f "${OPTIONS_JSON}" ]]; then
        val="$(jq -r --arg k "${key}" '.[$k] // empty' "${OPTIONS_JSON}" 2>/dev/null || true)"
    fi
    [[ -z "${val}" ]] && val="${def}"
    printf '%s' "${val}"
}

APPFLOWY_BASE_URL="$(opt APPFLOWY_BASE_URL http://homeassistant.local:9080)"
APPFLOWY_BASE_URL="${APPFLOWY_BASE_URL%/}"
GOTRUE_ADMIN_EMAIL="$(opt GOTRUE_ADMIN_EMAIL admin@example.com)"
GOTRUE_ADMIN_PASSWORD="$(opt GOTRUE_ADMIN_PASSWORD)"
GOTRUE_DISABLE_SIGNUP="$(opt GOTRUE_DISABLE_SIGNUP false)"
GOTRUE_MAILER_AUTOCONFIRM="$(opt GOTRUE_MAILER_AUTOCONFIRM true)"
RUST_LOG="$(opt RUST_LOG info)"
TZ_VALUE="$(opt TZ Europe/Bratislava)"
SMTP_HOST="$(opt SMTP_HOST)"
SMTP_PORT="$(opt SMTP_PORT)"
SMTP_USER="$(opt SMTP_USER)"
SMTP_PASSWORD="$(opt SMTP_PASSWORD)"
SMTP_FROM="$(opt SMTP_FROM "${GOTRUE_ADMIN_EMAIL}")"

# If no admin password is configured, derive a stable one from the JWT secret so
# the admin account is still usable and consistent across restarts.
if [[ -z "${GOTRUE_ADMIN_PASSWORD}" ]]; then
    GOTRUE_ADMIN_PASSWORD="$(printf '%s' "${GOTRUE_JWT_SECRET}" | sha256sum | cut -c1-24)"
    log "No GOTRUE_ADMIN_PASSWORD set — using a generated one (see the add-on logs below)."
    log "Admin login: ${GOTRUE_ADMIN_EMAIL} / ${GOTRUE_ADMIN_PASSWORD}"
fi

# ── Timezone ─────────────────────────────────────────────────────────────────
if [[ -n "${TZ_VALUE}" && -f "/usr/share/zoneinfo/${TZ_VALUE}" ]]; then
    ln -snf "/usr/share/zoneinfo/${TZ_VALUE}" /etc/localtime
    echo "${TZ_VALUE}" > /etc/timezone
fi

# ── 3. Derived service environment ───────────────────────────────────────────
# All services run on loopback; nginx is the only externally-reachable surface.
PG_URL="postgres://postgres:${POSTGRES_PASSWORD}@127.0.0.1:5432/postgres"
# ws:// or wss:// depending on the external scheme (http→ws, https→wss)
WS_ORIGIN="${APPFLOWY_BASE_URL/http/ws}"
WS_BASE_URL="${WS_ORIGIN}/ws/v2"

cat > "${ENV_FILE}" <<EOF
# Generated by afw-entrypoint.sh — do not edit by hand.
TZ=${TZ_VALUE}
RUST_LOG=${RUST_LOG}

# Shared secrets
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
GOTRUE_JWT_SECRET=${GOTRUE_JWT_SECRET}
APPFLOWY_S3_ACCESS_KEY=${APPFLOWY_S3_ACCESS_KEY}
APPFLOWY_S3_SECRET_KEY=${APPFLOWY_S3_SECRET_KEY}

# External surface
APPFLOWY_BASE_URL=${APPFLOWY_BASE_URL}
APPFLOWY_WEB_URL=${APPFLOWY_BASE_URL}
APPFLOWY_WEBSOCKET_BASE_URL=${WS_BASE_URL}

# PostgreSQL / Redis
APPFLOWY_DATABASE_URL=${PG_URL}
APPFLOWY_DATABASE_MAX_CONNECTIONS=40
APPFLOWY_REDIS_URI=redis://127.0.0.1:6379

# Object storage (bundled MinIO)
APPFLOWY_S3_USE_MINIO=true
APPFLOWY_S3_CREATE_BUCKET=true
APPFLOWY_S3_BUCKET=appflowy
APPFLOWY_S3_REGION=
APPFLOWY_S3_MINIO_URL=http://127.0.0.1:9000
APPFLOWY_S3_PRESIGNED_URL_ENDPOINT=${APPFLOWY_BASE_URL}/minio-api
MINIO_ROOT_USER=${APPFLOWY_S3_ACCESS_KEY}
MINIO_ROOT_PASSWORD=${APPFLOWY_S3_SECRET_KEY}
MINIO_BROWSER_REDIRECT_URL=${APPFLOWY_BASE_URL}/minio

# GoTrue (auth)
DATABASE_URL=${PG_URL}?search_path=auth
API_EXTERNAL_URL=${APPFLOWY_BASE_URL}/gotrue
GOTRUE_DB_DRIVER=postgres
GOTRUE_SITE_URL=appflowy-flutter://
GOTRUE_URI_ALLOW_LIST=**
GOTRUE_JWT_EXP=604800
GOTRUE_JWT_ADMIN_GROUP_NAME=supabase_admin
GOTRUE_ADMIN_EMAIL=${GOTRUE_ADMIN_EMAIL}
GOTRUE_ADMIN_PASSWORD=${GOTRUE_ADMIN_PASSWORD}
GOTRUE_DISABLE_SIGNUP=${GOTRUE_DISABLE_SIGNUP}
GOTRUE_MAILER_AUTOCONFIRM=${GOTRUE_MAILER_AUTOCONFIRM}
GOTRUE_MAILER_URLPATHS_CONFIRMATION=/gotrue/verify
GOTRUE_MAILER_URLPATHS_INVITE=/gotrue/verify
GOTRUE_MAILER_URLPATHS_RECOVERY=/gotrue/verify
GOTRUE_MAILER_URLPATHS_EMAIL_CHANGE=/gotrue/verify
GOTRUE_SMTP_HOST=${SMTP_HOST}
GOTRUE_SMTP_PORT=${SMTP_PORT}
GOTRUE_SMTP_USER=${SMTP_USER}
GOTRUE_SMTP_PASS=${SMTP_PASSWORD}
GOTRUE_SMTP_ADMIN_EMAIL=${SMTP_FROM}
PORT=9999

# AppFlowy Cloud API
APPFLOWY_ENVIRONMENT=production
APPFLOWY_ACCESS_CONTROL=true
APPFLOWY_GOTRUE_BASE_URL=http://127.0.0.1:9999
APPFLOWY_GOTRUE_JWT_SECRET=${GOTRUE_JWT_SECRET}
APPFLOWY_MAILER_SMTP_HOST=${SMTP_HOST}
APPFLOWY_MAILER_SMTP_PORT=${SMTP_PORT}
APPFLOWY_MAILER_SMTP_USERNAME=${SMTP_USER}
APPFLOWY_MAILER_SMTP_EMAIL=${SMTP_FROM}
APPFLOWY_MAILER_SMTP_PASSWORD=${SMTP_PASSWORD}
APPFLOWY_MAILER_SMTP_TLS_KIND=none
AI_ENABLED=false

# AppFlowy worker
APPFLOWY_WORKER_ENVIRONMENT=production
APPFLOWY_WORKER_REDIS_URL=redis://127.0.0.1:6379
APPFLOWY_WORKER_DATABASE_URL=${PG_URL}
APPFLOWY_WORKER_DATABASE_NAME=postgres
APPFLOWY_WORKER_IMPORT_TICK_INTERVAL=30
EOF
chmod 600 "${ENV_FILE}"

# ── 4. PostgreSQL bootstrap ──────────────────────────────────────────────────
mkdir -p "${PGDATA}"
chown -R postgres:postgres "${PGDATA}" "${CONFIG_DIR}/minio-data" "${CONFIG_DIR}/redis"
chmod 700 "${PGDATA}"

if [[ ! -s "${PGDATA}/PG_VERSION" ]]; then
    log "Initialising PostgreSQL data directory…"
    PWFILE="$(mktemp)"
    printf '%s' "${POSTGRES_PASSWORD}" > "${PWFILE}"
    chown postgres "${PWFILE}"
    gosu postgres initdb -D "${PGDATA}" -U postgres \
        --auth-local=trust --auth-host=scram-sha-256 --pwfile="${PWFILE}"
    rm -f "${PWFILE}"
    {
        echo "listen_addresses = '127.0.0.1'"
        echo "port = 5432"
    } >> "${PGDATA}/postgresql.conf"

    log "Creating extensions and auth schema…"
    gosu postgres pg_ctl -D "${PGDATA}" -w -t 60 start
    gosu postgres psql -v ON_ERROR_STOP=1 --username postgres <<'SQL'
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA IF NOT EXISTS auth AUTHORIZATION postgres;
SQL
    gosu postgres pg_ctl -D "${PGDATA}" -w -t 60 stop
    log "PostgreSQL initialised."
fi

# ── 5. Render nginx gateway + ingress landing page ───────────────────────────
INGRESS_ENTRY=""
if [[ -n "${SUPERVISOR_TOKEN:-}" ]]; then
    ADDON_INFO="$(curl -fsSL -H "Authorization: Bearer ${SUPERVISOR_TOKEN}" \
        "http://supervisor/addons/self/info" 2>/dev/null || true)"
    [[ -n "${ADDON_INFO}" ]] && \
        INGRESS_ENTRY="$(echo "${ADDON_INFO}" | jq -r '.data.ingress_entry // ""' 2>/dev/null || true)"
fi
log "Ingress entry: ${INGRESS_ENTRY:-/}"

sed "s|__APPFLOWY_BASE_URL__|${APPFLOWY_BASE_URL}|g; s|__INGRESS_ENTRY__|${INGRESS_ENTRY}|g" \
    /usr/share/appflowy/ingress-index.html.tmpl > /run/appflowy/ingress-index.html

# ── Inject runtime config into the web front-end ─────────────────────────────
# The SPA reads window.__APP_CONFIG__ at boot to learn its backend URLs. The
# container filesystem resets to the pristine image on every start, so this
# injection is done fresh each boot.
WEB_INDEX="/opt/appflowy-web/index.html"
if [[ -f "${WEB_INDEX}" ]] && ! grep -q "__APP_CONFIG__" "${WEB_INDEX}"; then
    # Derive the backend URLs from the origin the browser actually loaded the
    # page from, so the web front-end works at whatever host/IP is used to reach
    # the add-on (LAN IP, hostname, reverse-proxied domain) without depending on
    # APPFLOWY_BASE_URL matching. All backends are same-origin behind the gateway.
    WEB_CFG='<script>(function(){var o=location.origin,w=(location.protocol==="https:"?"wss":"ws")+"://"+location.host;window.__APP_CONFIG__={APPFLOWY_BASE_URL:o,APPFLOWY_GOTRUE_BASE_URL:o+"/gotrue",APPFLOWY_WS_BASE_URL:w+"/ws/v2"};})();</script>'
    sed -i "s#</head>#${WEB_CFG}</head>#" "${WEB_INDEX}"
    log "Injected web front-end config (origin-relative)."
fi

log "Starting services via supervisord…"
exec /usr/bin/supervisord -c /etc/supervisor/conf.d/appflowy.conf
